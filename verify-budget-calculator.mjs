import assert from 'node:assert/strict';
import './dist/budget-calculator.js';
const B=globalThis.TripBudget,p={budget:2500,nights:5,travellers:2};
const input={flights:1000,nightly:100,rooms:2,foodDaily:20,transport:100,extras:60,buffer:10};
const result=B.calculate(input,p);
assert.equal(result.status,'ready');
assert.equal(result.stay,1000);
assert.equal(result.food,240);
assert.equal(result.subtotal,2400);
assert.equal(result.buffer,240);
assert.equal(result.total,2640);
assert.equal(result.perPerson,1320);
assert.equal(result.remaining,-140);
assert.equal(result.withinBudget,false);
assert.equal(B.calculate(input,{...p,budget:2640}).remaining,0);
assert.equal(B.calculate(input,{...p,budget:2640}).withinBudget,true);
assert.equal(B.calculate({...input,rooms:1},p).stay,500);
assert.equal(B.calculate({...input,buffer:0},p).total,2400);
assert.equal(B.calculate({...input,flights:''},p).status,'incomplete');
assert.equal(B.calculate(B.defaults(null,p),p).status,'incomplete');
assert.equal(B.calculate({...input,flights:-1},p).status,'invalid');
assert.equal(B.calculate({...input,flights:Infinity},p).status,'invalid');
assert.equal(B.calculate({...input,nightly:1000001},p).status,'invalid');
assert.equal(B.calculate({...input,rooms:1.5},p).status,'invalid');
assert.equal(B.calculate({...input,buffer:101},p).status,'invalid');
const zero={flights:0,nightly:0,rooms:1,foodDaily:0,transport:0,extras:0,buffer:0};
assert.equal(B.calculate(zero,p).total,0);
const expedition=B.calculate({...zero,packageTotal:4000},p,true);
assert.equal(expedition.stay,4000);
assert.equal(expedition.total,4000);
const cents=B.calculate({...zero,flights:0.1,extras:0.2},p);
assert.equal(cents.total,0.3);
assert.equal(cents.remaining,2499.7);
const defaults=B.defaults({flights:500,nightly:90,rooms:2,food:300,activities:200},p);
assert.equal(defaults.foodDaily,'25');
assert.equal(B.calculate(defaults,p).food,300);
console.log('PASS: manual group totals, rooms and nights, food days, buffer, budget comparison, blank and invalid costs, zero-cost items, expedition packages, and currency rounding.');
